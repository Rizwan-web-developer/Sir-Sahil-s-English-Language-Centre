export type Dictionary = typeof en;

const dictionaries: Record<Locale, Dictionary> = {
  en,
  // TODO(urdu): add the Urdu dictionary when translations are approved.
  ur: en,
};

export function getDictionary(locale: Locale = defaultLocale): Dictionary {
  return dictionaries[locale];
}

/** Default dictionary — safe to use in components until a locale switcher exists. */
export const t = getDictionary();

export function sessionLabel(type: "conversation" | "grammar"): string {
  return t.sessions[type];
}

export function dayLabel(isoDay: number, short = false): string {
  const index = Math.min(Math.max(isoDay, 1), 7) - 1;
  return short ? t.days.short[index] : t.days.full[index];
}
